def V_min_of_x(x, mp2, lamp, lampp, lam=1.0, m2=1.0):
    """Depth of the potential at phase x = cos(2 theta), radial minimized.

    mu2 = m2 - mp2*x ; Lam = lam + lamp*(2x^2-1)/2 + lampp*x
    V_min = -mu2^2/(4 Lam) for mu2 > 0 (else v = 0, V = 0).
    Returns +inf where Lam <= 0 (unbounded direction -- draw rejected upstream).
    """
    mu2 = m2 - mp2 * x
    Lam = lam + lamp * (2.0 * x * x - 1.0) / 2.0 + lampp * x
    mu2 = np.maximum(mu2, 0.0)
    with np.errstate(divide="ignore", invalid="ignore"):
        V = -(mu2 * mu2) / (4.0 * Lam)
    return np.where(Lam > 0.0, V, np.inf)


def bounded(mp2, lamp, lampp, lam=1.0):
    """Quartic form positive for all theta: lam + lamp(2x^2-1)/2 + lampp x > 0."""
    x = np.linspace(-1.0, 1.0, 201)
    Lam = lam + lamp * (2.0 * x * x - 1.0) / 2.0 + lampp * x
    return Lam.min(axis=-1) > 1e-9


def minimize_flavon(mp2, lamp, lampp, lam=1.0, ngrid=4001):
    """Vectorized global minimization over x in [-1, 1] (grid + parabolic refine).

    Accepts scalar or 1-d arrays of coefficients. Returns (x*, theta*, v*, Vmin).
    """
    mp2 = np.atleast_1d(np.asarray(mp2, float))
    lamp = np.atleast_1d(np.asarray(lamp, float))
    lampp = np.atleast_1d(np.asarray(lampp, float))
    x = np.linspace(-1.0, 1.0, ngrid)
    V = V_min_of_x(x[None, :], mp2[:, None], lamp[:, None], lampp[:, None],
                   lam=lam)
    i = np.argmin(V, axis=1)
    # parabolic refinement (interior points only)
    ii = np.clip(i, 1, ngrid - 2)
    y0, y1, y2 = (V[np.arange(len(i)), ii - 1], V[np.arange(len(i)), ii],
                  V[np.arange(len(i)), ii + 1])
    denom = (y0 - 2 * y1 + y2)
    shift = np.where(np.abs(denom) > 1e-300, 0.5 * (y0 - y2) / denom, 0.0)
    shift = np.clip(shift, -1.0, 1.0)
    dx = x[1] - x[0]
    xstar = np.clip(x[ii] + shift * dx, -1.0, 1.0)
    xstar = np.where(i == 0, -1.0, np.where(i == ngrid - 1, 1.0, xstar))
    mu2 = np.maximum(1.0 - mp2 * xstar, 0.0)
    Lam = 1.0 * lam + lamp * (2 * xstar ** 2 - 1) / 2.0 + lampp * xstar
    vstar = np.sqrt(mu2 / (2.0 * Lam))
    Vstar = -(mu2 ** 2) / (4.0 * Lam)
    theta = 0.5 * np.arccos(np.clip(xstar, -1, 1))
    return xstar, theta, vstar, Vstar


def fold_pi(delta):
    """Fold an angle to [0, pi] (|Delta_CP| mod 2pi, using the +-theta* pair)."""
    d = np.mod(delta, 2.0 * np.pi)
    return np.where(d > np.pi, 2.0 * np.pi - d, d)


