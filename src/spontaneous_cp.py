def psi_wall_margin(delta_cp):
    """Collapse/domination margin of the psi (second-harmonic) walls vs Delta_CP.

    domain_wall_history.py used bias delta_V = 2 A_3 (implicitly |cos(dCP/2)|=1).
    With the two Z_2 minima psi = 0, pi (basis delta_2 = 0, delta_3 = -dCP/2):
        bias = |V(pi) - V(0)| = 2 A_3 |cos(Delta_CP/2)|.
    T_c ∝ sqrt(H_c) ∝ sqrt(bias)  =>  margin(dCP) = margin_0 sqrt(|cos(dCP/2)|).
    """
    rho = f_psi
    A2 = 0.5 * kappa2_bench * rho ** 4
    A3 = 0.25 * c3_bench * rho ** 6
    m2m = 2.0 * math.sqrt(A2) / f_psi
    sigma = 2.0 * m2m * f_psi ** 2
    cosfac = np.abs(np.cos(np.asarray(delta_cp) / 2.0))
    Hc = 2.0 * A3 * cosfac / sigma
    Tc = np.sqrt(Hc * MPL_GEV / (1.66 * math.sqrt(gstar)))
    Tdom2 = (A_WALL * sigma * 1.66 * math.sqrt(gstar) / MPL_GEV) / (
        math.pi ** 2 / 30.0 * gstar)
    Tdom = math.sqrt(Tdom2)
    return Tc / Tdom


def flavon_wall_tension_coeff(mp2, lamp, lampp, lam=1.0, npts=4000):
    """sigma_S = k * v_S^3 for the CP walls between theta* and its images.

    Canonical phase field chi = v theta at frozen v = v(theta*);
    sigma_hat = v^2 * int sqrt(2 (V(theta) - V_min)) dtheta along the lower of
    the two barrier paths (through theta = 0 or theta = pi/2).
    Returns k = sigma_hat / v_hat^3 (dimensionless; sigma_phys = k v_S^3).
    """
    xstar, tstar, vstar, Vstar = minimize_flavon(mp2, lamp, lampp, lam=lam)
    tstar, vstar, Vstar = float(tstar[0]), float(vstar[0]), float(Vstar[0])

    def Vth(th):
        x = np.cos(2 * th)
        mu2 = 1.0 - mp2 * x
        Lam = lam + lamp * (2 * x ** 2 - 1) / 2.0 + lampp * x
        return -mu2 * vstar ** 2 + Lam * vstar ** 4

    sig = []
    for a, b in [(-tstar, tstar), (tstar, np.pi - tstar)]:  # via 0, via pi/2
        th = np.linspace(a, b, npts)
        dV = np.maximum(Vth(th) - Vth(tstar), 0.0)
        sig.append(vstar * np.trapezoid(np.sqrt(2.0 * dV), th))
    return min(sig) / vstar ** 3, tstar, vstar


